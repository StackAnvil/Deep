    public static Optional<KeyEvent> key(final net.minecraft.client.input.KeyEvent event) {
        return fromScancode(event.key()).map(key -> new KeyEvent(key, modifiers(event.modifiers())));
    }

    public static MouseButtonEvent mouse(final net.minecraft.client.input.MouseButtonEvent event) {
        MouseButton button = switch (event.button()) {
            case InputConstants.MOUSE_BUTTON_RIGHT -> MouseButton.RIGHT;
            case InputConstants.MOUSE_BUTTON_MIDDLE -> MouseButton.MIDDLE;
            default -> MouseButton.LEFT;
        };
        return new MouseButtonEvent((float) event.x(), (float) event.y(), button, modifiers(event.modifiers()), Set.of());
    }

    public static Set<ModifierKey> modifiers(final int modifierFlags) {
        Set<ModifierKey> modifiers = EnumSet.noneOf(ModifierKey.class);
        if ((modifierFlags & InputConstants.MOD_SHIFT) != 0) modifiers.add(ModifierKey.SHIFT);
        if ((modifierFlags & InputConstants.MOD_CONTROL) != 0) modifiers.add(ModifierKey.CONTROL);
        if ((modifierFlags & InputConstants.MOD_ALT) != 0) modifiers.add(ModifierKey.ALT);
        if ((modifierFlags & InputConstants.MOD_SUPER) != 0) modifiers.add(ModifierKey.SUPER);
        return modifiers;
    }

